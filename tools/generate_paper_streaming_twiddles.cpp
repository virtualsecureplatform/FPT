// Compile-time twiddle image for the guarded32 arithmetic schedule.
#include <cfenv>
#include <cmath>
#include <cstdint>
#include <fstream>
#include <numbers>
#include <stdexcept>
#include <vector>

static void emit(std::ostream &out,const char *name,const std::vector<std::int64_t> &values)
{
    out<<"localparam logic signed [27:0] "<<name<<" [0:"<<values.size()-1<<"] = '{\n";
    for(unsigned i=0;i<values.size();++i) {
        const auto value=values[i];
        out<<"  "<<(value<0?"-":"")<<"28'sd"<<(value<0?-value:value)
           <<(i+1==values.size()?"\n":",\n");
    }
    out<<"};\n";
}
int main(int argc,char **argv)
{
    if(argc!=2)throw std::invalid_argument("usage: generate-twiddles OUTPUT.svh");
    std::fesetround(FE_TONEAREST);
    std::ofstream out(argv[1]);
    if(!out)throw std::runtime_error("cannot write twiddle image");
    out<<"// Generated by tools/generate_paper_streaming_twiddles.cpp; signed F=26.\n";
    std::vector<std::int64_t> real,imag;
    auto append=[&](long double angle) {
        real.push_back(std::int64_t(std::nearbyint(std::ldexp(std::cos(angle),26))));
        imag.push_back(std::int64_t(std::nearbyint(std::ldexp(std::sin(angle),26))));
    };
    for(unsigned length:{4u,16u,64u,256u})for(unsigned leg=0;leg<4;++leg)
        for(unsigned j=0;j<length/4;++j)
            append(-2*std::numbers::pi_v<long double>*leg*j/length);
    emit(out,"PAPER_FFT_COS",real);emit(out,"PAPER_FFT_SIN",imag);
    real.clear();imag.clear();
    for(unsigned j=0;j<256;++j)append(std::numbers::pi_v<long double>*j/512);
    emit(out,"PAPER_TWIST_COS",real);emit(out,"PAPER_TWIST_SIN",imag);
    if(!out)throw std::runtime_error("twiddle image write failed");
}
